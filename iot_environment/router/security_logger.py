
"""
Central security-event logger for the IoT cyber range.

FUTURE EXTENSIONS:
- Connect these events to shared/events.json or a central event collector.
- Add device IDs when a device registry is implemented.
- Connect events to the defender agent for attack detection and response.
- Use persistent storage if events must survive router restarts.

IMPORTANT:
This logger records events generated by the router application.
It does not automatically capture real network packets or Docker traffic.
"""

from datetime import datetime, timezone
from threading import Lock
from uuid import uuid4

from config import MAX_SECURITY_EVENTS


# In-memory event history for the initial prototype.
# Events are lost when the router process restarts.
_security_events = []
_lock = Lock()


def log_event(event_type, details=None, severity="INFO"):
    """
    Record a router security event.

    Args:
        event_type: Event category, e.g. TRAFFIC_BLOCKED.
        details: Additional information about the event.
        severity: INFO, WARNING, or CRITICAL.
    """
    if severity not in {"INFO", "WARNING", "CRITICAL"}:
        severity = "INFO"

    event = {
        "event_id": str(uuid4()),
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "source": "iot_router",
        "event_type": event_type,
        "severity": severity,
        "details": details if isinstance(details, dict) else {}
    }

    with _lock:
        _security_events.append(event)

        # Retain only the newest events to prevent unlimited memory growth.
        if len(_security_events) > MAX_SECURITY_EVENTS:
            del _security_events[:-MAX_SECURITY_EVENTS]

    return event


def get_recent_events(limit=100):
    """Return the newest security events."""
    try:
        limit = int(limit)
    except (TypeError, ValueError):
        limit = 100

    limit = max(1, min(limit, MAX_SECURITY_EVENTS))

    with _lock:
        return list(reversed(_security_events[-limit:]))


def clear_events():
    """Clear in-memory events, useful when resetting a test episode."""
    with _lock:
        _security_events.clear()
